-- +goose Up
-- The installation's single sign-on settings (Entra design D1,
-- docs/superpowers/specs/2026-10-19-entra-design.md): the workforce OpenID
-- Connect provider and the SCIM credential, which were the OIDC_* and SCIM_*
-- environment variables until now and are one row an Owner edits from here
-- on. Every reader — the session query, sign-in, the SCIM bearer check, the
-- relying party, the status endpoints, the authority mode — reads it through
-- a 20-second in-process cache, so a save is in effect on every replica
-- without a restart.
--
-- The row is its own table, not columns on system_settings: the session
-- query reads "is SCIM on" on every request, and a sealed secret and two
-- digests should not travel with the maintenance flag and the time zone.
-- version is 0 until the row is first written; it is what PUT
-- /owner/sso/oidc's If-Match is compared with, what the relying party is
-- rebuilt on when it moves, and what tells the API's first start whether to
-- import the variables (once, imported_from_environment then true). The
-- client secret is sealed under the secrets purpose
-- identity/oidc-client-secret and never answered; the SCIM token is
-- generated by the server, answered once and kept as its SHA-256 alone, the
-- previous one with the instant its overlap ends. The workload token file is
-- a path, read afresh at every sign-in. By identity's baseline style a CHECK
-- holds the provider to its two values; the rest of the rules — the
-- authority's form per provider, the client id's, the secret or the file,
-- the domains, the overlap's 24 hours — are the module's validation, as they
-- were the config loader's.
CREATE TABLE identity.sso_settings (
    id                          smallint     PRIMARY KEY CHECK (id = 1),
    version                     integer      NOT NULL DEFAULT 0,   -- 0: never written
    oidc_enabled                boolean      NOT NULL DEFAULT false,
    oidc_provider               varchar(10)  CHECK (oidc_provider IN ('entra', 'google')),
    oidc_authority              varchar(200),
    oidc_client_id              varchar(200),
    oidc_client_secret_sealed   bytea,                             -- identity/oidc-client-secret
    oidc_client_secret_set_at   timestamptz,
    oidc_workload_token_file    varchar(500),
    oidc_allowed_domains        text[]       NOT NULL DEFAULT '{}',
    oidc_display_name           varchar(100),
    scim_enabled                boolean      NOT NULL DEFAULT false,
    scim_token_sha256           bytea,
    scim_token_set_at           timestamptz,
    scim_previous_token_sha256  bytea,
    scim_previous_expires_at    timestamptz,
    imported_from_environment   boolean      NOT NULL DEFAULT false,
    updated_at                  timestamptz  NOT NULL,
    updated_by_user_id          uuid
);

-- +goose Down
-- The Down drops the row, and with it the sealed secret and the SCIM
-- digests: a binary from before this migration reads the OIDC_* and SCIM_*
-- variables again, so an installation rolling back sets them first (a SCIM
-- token issued here is not recoverable and is replaced by a new one).
DROP TABLE identity.sso_settings;
