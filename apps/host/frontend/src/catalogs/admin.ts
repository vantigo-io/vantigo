type HostTranslationFunction = (key: string) => string;

export const hostBuiltInRoleTranslationKeys = {
  User: { displayNameKey: "admin.userRole", descriptionKey: "admin.userRoleDescription" },
  Owner: { displayNameKey: "admin.ownerRole", descriptionKey: "admin.ownerRoleDescription" },
} as const;

export const getHostBuiltInRoleTranslation = (role: string) =>
  hostBuiltInRoleTranslationKeys[role as keyof typeof hostBuiltInRoleTranslationKeys];

export const translateHostRole = (role: string, t: HostTranslationFunction, fallback = role): string => {
  const translation = getHostBuiltInRoleTranslation(role);
  return translation ? t(translation.displayNameKey) : fallback;
};

export const translateHostRoleDescription = (role: string, fallback: string, t: HostTranslationFunction): string => {
  const translation = getHostBuiltInRoleTranslation(role);
  return translation ? t(translation.descriptionKey) : fallback;
};

